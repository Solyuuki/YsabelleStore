def main() -> int:
    args = parse_args()
    input_path = (REPO_ROOT / args.input).resolve() if not Path(args.input).is_absolute() else Path(args.input)
    output = (REPO_ROOT / args.output).resolve() if not Path(args.output).is_absolute() else Path(args.output)

    if args.holdout <= 0:
        raise ValueError("--holdout must be greater than zero.")
    if args.min_train < 24:
        raise ValueError("--min-train must be at least 24 for the current SARIMA implementation.")
    if args.seasonal_period <= 1:
        raise ValueError("--seasonal-period must be greater than one.")
    if not input_path.exists():
        raise FileNotFoundError(
            f"Validation input not found: {input_path}. Run npm run thesis:sarima:export first."
        )

    output.mkdir(parents=True, exist_ok=True)
    frame = load_input(input_path)

    product_results: list[ProductResult] = []
    detailed_rows: list[dict[str, Any]] = []
    exclusions: list[dict[str, str]] = []

    for product_id, group in frame.groupby("product_id", sort=True):
        try:
            result, rows = validate_product(
                group,
                holdout=args.holdout,
                min_train=args.min_train,
                seasonal_period=args.seasonal_period,
            )
            product_results.append(result)
            detailed_rows.extend(rows)
        except Exception as exc:  # noqa: BLE001 - every exclusion is retained as thesis evidence.
            first = group.iloc[0]
            exclusions.append(
                {
                    "product_id": str(product_id),
                    "product_name": str(first["product_name"]),
                    "reason": str(exc),
                }
            )

    exclusions_frame = pd.DataFrame(exclusions, columns=["product_id", "product_name", "reason"])
    exclusions_frame.to_csv(output / "excluded_products.csv", index=False)

    if not product_results:
        metadata = {
            "git_commit": git_sha(),
            "input": str(input_path),
            "input_rows": len(frame),
            "input_products": int(frame["product_id"].nunique()),
            "successful_products": 0,
            "excluded_products": len(exclusions),
            "holdout_months": args.holdout,
            "minimum_training_observations": args.min_train,
            "seasonal_period": args.seasonal_period,
            "status": "FAILED_NO_ELIGIBLE_PRODUCTS",
        }
        (output / "validation_metadata.json").write_text(
            json.dumps(metadata, indent=2) + "\n", encoding="utf-8"
        )
        print(json.dumps(metadata, indent=2))
        return 2

    product_metrics = pd.DataFrame([asdict(result) for result in product_results])
    detailed = pd.DataFrame(detailed_rows)
    product_metrics.to_csv(output / "product_metrics.csv", index=False)
    detailed.to_csv(output / "detailed_calculations.csv", index=False)

    overall = metric_bundle(
        detailed["actual"].to_numpy(dtype=float),
        detailed["forecast"].to_numpy(dtype=float),
    )
    if not all(overall["verification"].values()):
        raise RuntimeError("Overall metric cross-check failed.")

    summary = {
        "mae": round(float(overall["mae"]), 4),
        "mape": round(float(overall["mape"]), 4) if overall["mape"] is not None else None,
        "rmse": round(float(overall["rmse"]), 4),
        "mape_valid_observations": int(overall["mape_valid_observations"]),
        "zero_actual_observations_excluded_from_mape": int(overall["zero_actual_observations"]),
        "validated_product_month_observations": len(detailed),
        "validated_products": len(product_metrics),
    }
    pd.DataFrame([summary]).to_csv(output / "summary_metrics.csv", index=False)

    representative_id = select_representative(product_metrics, args.plot_product_id)
    save_metric_figures(summary, output)
    representative_name = save_forecast_figures(detailed, representative_id, output)

    metadata = {
        "status": "COMPLETE",
        "git_commit": git_sha(),
        "input": str(input_path),
        "input_rows": len(frame),
        "input_products": int(frame["product_id"].nunique()),
        "successful_products": len(product_metrics),
        "excluded_products": len(exclusions),
        "holdout_months": args.holdout,
        "minimum_training_observations": args.min_train,
        "seasonal_period": args.seasonal_period,
        "metric_library": "scikit-learn",
        "metric_cross_check": "NumPy formula cross-check; all summary checks passed.",
        "mape_policy": "Actual=0 observations are retained for MAE/RMSE and excluded only from MAPE.",
        "representative_product_id": representative_id,
        "representative_product_name": representative_name,
        "representative_selection": (
            "Explicit --plot-product-id"
            if args.plot_product_id
            else "Successful product whose MAPE is closest to the median product MAPE; product ID breaks ties."
        ),
        "environment": {
            "python": sys.version.split()[0],
            "sarima_fit_timeout_seconds": os.getenv("SARIMA_FIT_TIMEOUT_SECONDS", "default"),
        },
    }
    (output / "validation_metadata.json").write_text(
        json.dumps(metadata, indent=2) + "\n", encoding="utf-8"
    )

    report_lines = [
        "YSABELLE STORE - SARIMA THESIS VALIDATION",
        "==========================================",
        f"Status: COMPLETE",
        f"Validated products: {summary['validated_products']}",
        f"Excluded products: {len(exclusions)}",
        f"Validated product-month observations: {summary['validated_product_month_observations']}",
        "",
        "OVERALL HOLD-OUT METRICS",
        f"MAE  : {summary['mae']:.4f} units",
        f"MAPE : {'N/A' if summary['mape'] is None else f'{summary['mape']:.4f}%'}",
        f"RMSE : {summary['rmse']:.4f} units",
        "",
        f"MAPE-valid observations: {summary['mape_valid_observations']}",
        f"Zero-actual observations excluded from MAPE only: {summary['zero_actual_observations_excluded_from_mape']}",
        "",
        "INDEPENDENT CROSS-CHECK",
        f"MAE  : {'PASS' if overall['verification']['mae'] else 'FAIL'}",
        f"MAPE : {'PASS' if overall['verification']['mape'] else 'FAIL'}",
        f"RMSE : {'PASS' if overall['verification']['rmse'] else 'FAIL'}",
        "",
        f"Representative product for product-level figures: {representative_name} ({representative_id})",
        f"Evidence directory: {output}",
    ]
    (output / "validation_report.txt").write_text("\n".join(report_lines) + "\n", encoding="utf-8")
    save_html_report(output, summary, metadata, representative_name, exclusions_frame)

    print("\n".join(report_lines))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
