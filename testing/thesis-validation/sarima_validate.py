@dataclass
class ProductResult:
    product_id: str
    product_name: str
    category: str
    observations: int
    training_observations: int
    testing_observations: int
    training_start: str
    training_end: str
    testing_start: str
    testing_end: str
    order: str
    seasonal_order: str
    aic: float
    converged: bool
    mae: float
    mape: float | None
    rmse: float
    mape_valid_observations: int
    zero_actual_observations: int


