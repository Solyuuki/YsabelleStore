def ensure_continuous_months(periods: pd.Series) -> bool:
    if periods.empty:
        return False
    parsed = pd.PeriodIndex(periods.astype(str), freq="M")
    expected = pd.period_range(parsed.min(), parsed.max(), freq="M")
    return parsed.is_unique and list(parsed) == list(expected)


def metric_bundle(actual: np.ndarray, forecast: np.ndarray) -> dict[str, Any]:
    actual = np.asarray(actual, dtype=float)
    forecast = np.asarray(forecast, dtype=float)

    if actual.shape != forecast.shape or actual.size == 0:
        raise ValueError("Actual and forecast arrays must be non-empty and have identical shapes.")

    mae_sklearn = float(mean_absolute_error(actual, forecast))
    rmse_sklearn = float(root_mean_squared_error(actual, forecast))

    nonzero_mask = actual != 0
    mape_sklearn: float | None = None
    if bool(nonzero_mask.any()):
        mape_sklearn = float(
            mean_absolute_percentage_error(actual[nonzero_mask], forecast[nonzero_mask]) * 100
        )

    residual = actual - forecast
    mae_manual = float(np.mean(np.abs(residual)))
    rmse_manual = float(np.sqrt(np.mean(np.square(residual))))
    mape_manual: float | None = None
    if bool(nonzero_mask.any()):
        mape_manual = float(
            np.mean(np.abs(residual[nonzero_mask] / actual[nonzero_mask])) * 100
        )

    verification = {
        "mae": bool(np.isclose(mae_sklearn, mae_manual, rtol=1e-10, atol=1e-10)),
        "rmse": bool(np.isclose(rmse_sklearn, rmse_manual, rtol=1e-10, atol=1e-10)),
        "mape": (
            mape_sklearn is None
            and mape_manual is None
            or (
                mape_sklearn is not None
                and mape_manual is not None
                and bool(np.isclose(mape_sklearn, mape_manual, rtol=1e-10, atol=1e-10))
            )
        ),
    }

    return {
        "mae": mae_sklearn,
        "rmse": rmse_sklearn,
        "mape": mape_sklearn,
        "manual_mae": mae_manual,
        "manual_rmse": rmse_manual,
        "manual_mape": mape_manual,
        "mape_valid_observations": int(nonzero_mask.sum()),
        "zero_actual_observations": int((~nonzero_mask).sum()),
        "verification": verification,
    }


def git_sha() -> str | None:
    try:
        return subprocess.check_output(
            ["git", "rev-parse", "HEAD"],
            cwd=REPO_ROOT,
            text=True,
            stderr=subprocess.DEVNULL,
        ).strip()
    except (OSError, subprocess.SubprocessError):
        return None


def load_input(path: Path) -> pd.DataFrame:
    frame = pd.read_csv(path)
    missing = sorted(REQUIRED_COLUMNS.difference(frame.columns))
    if missing:
        raise ValueError(f"Input CSV is missing required column(s): {', '.join(missing)}")

    frame = frame.copy()
    frame["product_id"] = frame["product_id"].astype(str)
    frame["product_name"] = frame["product_name"].astype(str)
    frame["category"] = frame["category"].astype(str)
    frame["period"] = frame["period"].astype(str)
    frame["quantity_sold"] = pd.to_numeric(frame["quantity_sold"], errors="raise")

    if not np.isfinite(frame["quantity_sold"].to_numpy(dtype=float)).all():
        raise ValueError("quantity_sold contains non-finite values.")
    if (frame["quantity_sold"] < 0).any():
        raise ValueError("quantity_sold contains negative values.")

    frame["_period"] = pd.PeriodIndex(frame["period"], freq="M")
    return frame.sort_values(["product_id", "_period"]).reset_index(drop=True)


def validate_product(
    group: pd.DataFrame,
    holdout: int,
    min_train: int,
    seasonal_period: int,
) -> tuple[ProductResult, list[dict[str, Any]]]:
    group = group.sort_values("_period").reset_index(drop=True)
    product_id = str(group.iloc[0]["product_id"])
    product_name = str(group.iloc[0]["product_name"])
    category = str(group.iloc[0]["category"])

    if not ensure_continuous_months(group["period"]):
        raise ValueError("monthly series is not chronological, unique, and continuous")

    minimum_required = min_train + holdout
    if len(group) < minimum_required:
        raise ValueError(
            f"requires at least {minimum_required} observations ({min_train} training + {holdout} testing); found {len(group)}"
        )

    train = group.iloc[:-holdout].copy()
    test = group.iloc[-holdout:].copy()

    if len(train) < min_train:
        raise ValueError(f"training set has only {len(train)} observations")

    train_values = train["quantity_sold"].to_numpy(dtype=float)
    actual = test["quantity_sold"].to_numpy(dtype=float)

    result = fit_sarima(
        train_values.tolist(),
        horizon=holdout,
        seasonal_period=seasonal_period,
        start_period=str(train.iloc[0]["period"]),
    )
    forecast = np.asarray(result.forecast, dtype=float)

    metrics = metric_bundle(actual, forecast)
    if not all(metrics["verification"].values()):
        raise RuntimeError("independent metric cross-check failed")

    detailed_rows: list[dict[str, Any]] = []
    for index, (_, row) in enumerate(test.iterrows()):
        actual_value = float(row["quantity_sold"])
        forecast_value = float(forecast[index])
        residual = actual_value - forecast_value
        detailed_rows.append(
            {
                "product_id": product_id,
                "product_name": product_name,
                "category": category,
                "period": str(row["period"]),
                "actual": actual_value,
                "forecast": forecast_value,
                "residual": residual,
                "absolute_error": abs(residual),
                "squared_error": residual * residual,
                "absolute_percentage_error": (
                    abs(residual / actual_value) * 100 if actual_value != 0 else None
                ),
                "order": str(tuple(result.order)),
                "seasonal_order": str(tuple(result.seasonal_order)),
                "aic": result.aic,
                "converged": result.converged,
            }
        )

    product_result = ProductResult(
        product_id=product_id,
        product_name=product_name,
        category=category,
        observations=len(group),
        training_observations=len(train),
        testing_observations=len(test),
        training_start=str(train.iloc[0]["period"]),
        training_end=str(train.iloc[-1]["period"]),
        testing_start=str(test.iloc[0]["period"]),
        testing_end=str(test.iloc[-1]["period"]),
        order=str(tuple(result.order)),
        seasonal_order=str(tuple(result.seasonal_order)),
        aic=float(result.aic),
        converged=bool(result.converged),
        mae=float(metrics["mae"]),
        mape=float(metrics["mape"]) if metrics["mape"] is not None else None,
        rmse=float(metrics["rmse"]),
        mape_valid_observations=int(metrics["mape_valid_observations"]),
        zero_actual_observations=int(metrics["zero_actual_observations"]),
    )
    return product_result, detailed_rows


def select_representative(
    product_metrics: pd.DataFrame, requested_product_id: str | None
) -> str:
    if requested_product_id is not None:
        matches = product_metrics[product_metrics["product_id"] == requested_product_id]
        if matches.empty:
            raise ValueError(
                f"Requested plot product {requested_product_id!r} is not in successful validation results."
            )
        return requested_product_id

    with_mape = product_metrics.dropna(subset=["mape"]).sort_values(
        ["mape", "product_id"]
    )
    if not with_mape.empty:
        target = float(median(with_mape["mape"].astype(float).tolist()))
        ranked = with_mape.assign(distance=(with_mape["mape"] - target).abs()).sort_values(
            ["distance", "product_id"]
        )
        return str(ranked.iloc[0]["product_id"])

    ranked = product_metrics.sort_values(["mae", "product_id"])
    return str(ranked.iloc[len(ranked) // 2]["product_id"])


def save_metric_figures(summary: dict[str, Any], output: Path) -> None:
    fig, ax = plt.subplots(figsize=(7, 4.5))
    labels = ["MAE", "RMSE"]
    values = [summary["mae"], summary["rmse"]]
    bars = ax.bar(labels, values)
    ax.set_ylabel("Units of monthly quantity sold")
    ax.set_title("SARIMA Forecast Error: MAE and RMSE")
    ax.bar_label(bars, fmt="%.4f")
    fig.tight_layout()
    fig.savefig(output / "mae_rmse_units.png", dpi=180)
    plt.close(fig)

    fig, ax = plt.subplots(figsize=(7, 4.5))
    if summary["mape"] is None:
        ax.text(0.5, 0.5, "MAPE unavailable\n(no non-zero actual observations)", ha="center", va="center")
        ax.set_axis_off()
    else:
        bars = ax.bar(["MAPE"], [summary["mape"]])
        ax.set_ylabel("Percentage error (%)")
        ax.set_title("SARIMA Mean Absolute Percentage Error")
        ax.bar_label(bars, fmt="%.4f%%")
    fig.tight_layout()
    fig.savefig(output / "mape_percentage.png", dpi=180)
    plt.close(fig)


def save_forecast_figures(
    detailed: pd.DataFrame,
    representative_id: str,
    output: Path,
) -> str:
    overall = (
        detailed.groupby("period", as_index=False)[["actual", "forecast"]]
        .sum()
        .sort_values("period")
    )
    fig, ax = plt.subplots(figsize=(10, 5.5))
    ax.plot(overall["period"], overall["actual"], marker="o", label="Actual")
    ax.plot(overall["period"], overall["forecast"], marker="o", label="SARIMA Forecast")
    ax.set_xlabel("Testing month")
    ax.set_ylabel("Aggregated quantity sold")
    ax.set_title("Actual vs Forecasted Demand Across Validated Products")
    ax.legend()
    ax.tick_params(axis="x", rotation=45)
    fig.tight_layout()
    fig.savefig(output / "actual_vs_forecast_overall.png", dpi=180)
    plt.close(fig)

    representative = detailed[detailed["product_id"] == representative_id].sort_values("period")
    representative_name = str(representative.iloc[0]["product_name"])

    fig, ax = plt.subplots(figsize=(10, 5.5))
    ax.plot(representative["period"], representative["actual"], marker="o", label="Actual")
    ax.plot(
        representative["period"],
        representative["forecast"],
        marker="o",
        label="SARIMA Forecast",
    )
    ax.set_xlabel("Testing month")
    ax.set_ylabel("Quantity sold")
    ax.set_title(f"Actual vs Forecast: {representative_name}")
    ax.legend()
    ax.tick_params(axis="x", rotation=45)
    fig.tight_layout()
    fig.savefig(output / "actual_vs_forecast_representative.png", dpi=180)
    plt.close(fig)

    fig, ax = plt.subplots(figsize=(10, 5.5))
    ax.axhline(0, linewidth=1)
    ax.plot(
        representative["period"],
        representative["residual"],
        marker="o",
    )
    ax.set_xlabel("Testing month")
    ax.set_ylabel("Residual (Actual - Forecast)")
    ax.set_title(f"Residual Behavior: {representative_name}")
    ax.tick_params(axis="x", rotation=45)
    fig.tight_layout()
    fig.savefig(output / "residual_plot_representative.png", dpi=180)
    plt.close(fig)

    fig, ax = plt.subplots(figsize=(8, 5))
    ax.hist(detailed["residual"].astype(float), bins=min(20, max(5, len(detailed) // 10)))
    ax.axvline(0, linewidth=1)
    ax.set_xlabel("Residual (Actual - Forecast)")
    ax.set_ylabel("Observation count")
    ax.set_title("Residual Distribution Across Validated Product-Months")
    fig.tight_layout()
    fig.savefig(output / "residual_distribution.png", dpi=180)
    plt.close(fig)

    return representative_name


